CREATE TABLE IF NOT EXISTS `bookings` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `pickup` varchar(255) NOT NULL,
  `dropoff` varchar(255) NOT NULL,
  `trip_type` varchar(20) NOT NULL DEFAULT 'one-way',
  `booking_category` varchar(20) DEFAULT 'standard',
  `flight_number` varchar(50) DEFAULT NULL,
  `child_seats` int(11) DEFAULT 0,
  `wheelchair_accessible` tinyint(1) DEFAULT 0,
  `payment_method` varchar(50) DEFAULT 'cash',
  `company_name` varchar(255) DEFAULT NULL,
  `account_reference` varchar(100) DEFAULT NULL,
  `via_stop` varchar(255) DEFAULT NULL,
  `journey_date` date NOT NULL,
  `journey_time` time NOT NULL,
  `return_date` date DEFAULT NULL,
  `return_time` time DEFAULT NULL,
  `passengers` int(11) NOT NULL,
  `luggage` int(11) NOT NULL,
  `taxi_count` int(11) NOT NULL DEFAULT 1,
  `vehicle_id` varchar(50) NOT NULL,
  `estimated_price` varchar(20) DEFAULT NULL,
  `distance` varchar(50) DEFAULT NULL,
  `customer_name` varchar(100) NOT NULL,
  `customer_email` varchar(100) NOT NULL,
  `customer_phone` varchar(50) NOT NULL,
  `notes` text,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
